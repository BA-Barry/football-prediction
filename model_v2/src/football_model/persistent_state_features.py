"""Reuse conditional GAS states as information, without averaging probabilities.

Only state extraction is implemented here. No learner is fitted and no deployed
forecast is changed. Learned global parameters must themselves predate each
row's information day; earlier rows retain missing fields rather than receiving
states generated by future-fitted parameters.
"""

from collections import Counter, defaultdict

from .persistent_goal_difference import PersistentGoalDifferenceFilter, _date, _rows


STATE_FEATURE_NAMES = (
    'gas_own_attack_state', 'gas_own_defence_state',
    'gas_opponent_attack_state', 'gas_opponent_defence_state',
    'gas_league_base_log_rate', 'gas_home_log_rate_effect',
)


def _features(own, opponent, league, *, is_home):
    a = own['state']
    b = opponent['state']
    return dict(zip(STATE_FEATURE_NAMES, (
        a[0] if a is not None else None, a[1] if a is not None else None,
        b[0] if b is not None else None, b[1] if b is not None else None,
        league['mu'], league['home'] if is_home else 0.,
    )))


def build_persistent_state_features(static, dynamics, history_after_static, targets):
    """Return all original targets with a dated, optional six-column state bank.

    `F` and `forecast_before_date` are accepted aliases and must agree if both
    are supplied. Observation dates are strictly less than F. State counts,
    missing reasons and parameter learning dates are metadata, not new numeric
    predictors. This bridge does not claim historical availability before the
    parameter estimation end, even when target fixture identities are known.
    """
    parameter_end = dynamics['training_max_date']
    _date(parameter_end)
    if static['training_max_date'] > parameter_end:
        raise ValueError("Global dynamics cannot predate static initialization")
    history = _rows(history_after_static, allow_empty=True)
    if history and history[0]['date'] <= static['training_max_date']:
        raise ValueError("State history overlaps static initialization")
    targets = list(targets)
    if len({r['match_id'] for r in targets}) != len(targets):
        raise ValueError("Duplicate target identifiers")
    indexed = []
    for index, row in enumerate(targets):
        cutoff = row.get('F', row.get('forecast_before_date'))
        _date(cutoff)
        _date(row['date'])
        if cutoff >= row['date']:
            raise ValueError("State information day must precede fixture day")
        if 'F' in row and 'forecast_before_date' in row and row['F'] != row['forecast_before_date']:
            raise ValueError("Conflicting target information dates")
        indexed.append((cutoff, row['match_id'], index, row))
    days = defaultdict(list)
    for row in history:
        days[row['date']].append(row)
    dates = sorted(days)
    state = PersistentGoalDifferenceFilter(static, dynamics['parameters'])
    cursor, result = 0, [None] * len(targets)
    for cutoff, _, index, row in sorted(indexed):
        context = {key: row[key] for key in ('match_id', 'date', 'competition', 'home', 'away')}
        context.update({'F': cutoff, 'feature_before_date': cutoff,
                        'parameter_training_max_date': parameter_end})
        if parameter_end >= cutoff:
            result[index] = {**context, 'available': False,
                'unavailable_reason': 'parameters_not_yet_fitted',
                'side_features': [dict.fromkeys(STATE_FEATURE_NAMES), dict.fromkeys(STATE_FEATURE_NAMES)],
                'state_history_max_date': None, 'explanation': None}
            continue
        while cursor < len(dates) and dates[cursor] < cutoff:
            state.observe_day(days[dates[cursor]])
            cursor += 1
        explanation = state.explain_state(row['competition'], row['home'], row['away'], cutoff)
        result[index] = {**context, 'available': explanation['available'],
            'unavailable_reason': None if explanation['available'] else 'no_observed_history',
            'side_features': [_features(explanation['home'], explanation['away'], explanation['league'], is_home=True),
                              _features(explanation['away'], explanation['home'], explanation['league'], is_home=False)],
            'state_history_max_date': explanation['state_history_max_date'], 'explanation': explanation}
    reasons = Counter(r['unavailable_reason'] or 'available' for r in result)
    return {'rows': result, 'metadata': {
        'target_count': len(result), 'feature_names': list(STATE_FEATURE_NAMES),
        'counts': dict(reasons), 'static_training_max_date': static['training_max_date'],
        'parameter_training_max_date': parameter_end,
        'clock': 'learned global parameters and every observation must be strictly earlier than F',
        'scope': 'state-only extraction; no fit, probability fusion or forecast replacement',
        'unknown': 'retain targets; unavailable numerical fields are None, never neutral known strength',
        'metadata_not_predictors': ['availability', 'missing reason', 'state counts', 'learning dates'],
    }}

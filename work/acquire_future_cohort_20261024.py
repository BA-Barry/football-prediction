"""Acquire source-only future EPL cohort, never forecast probabilities."""
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone, timedelta
import json
from pathlib import Path
from project_paths import PROJECT_ROOT as REPOSITORY_ROOT
import sys

ROOT = REPOSITORY_ROOT
sys.path.insert(0, str(ROOT / "work"))
from observe_batch_results_20261024 import download, write_json, stamp

NAME = {"Bournemouth": "AFC Bournemouth", "Brighton": "Brighton & Hove Albion",
        "Leeds": "Leeds United", "Man City": "Manchester City", "Man Utd": "Manchester United",
        "Newcastle": "Newcastle United", "Nott'm Forest": "Nottingham Forest", "Spurs": "Tottenham Hotspur"}


def main():
    now = datetime.now(timezone.utc)
    dest = ROOT / "data/prematch-intelligence" / now.strftime("NEW20261024_cohort_%Y%m%dT%H%M%S%fZ")
    dest.mkdir()
    sources = {}
    with ThreadPoolExecutor(max_workers=2) as pool:
        for label, body, metadata in pool.map(download, [
            ("fixtures", "https://fantasy.premierleague.com/api/fixtures/"),
            ("bootstrap", "https://fantasy.premierleague.com/api/bootstrap-static/")]):
            if body:
                (dest / metadata["raw_path"]).write_bytes(body)
            sources[label] = metadata
    write_json(dest / "source_metadata.json", {"recorded_at": stamp(), "sources": sources,
        "limits": ["Receipt is not source publication time. Nonzero cache Age retained.",
                   "No model or market or LLM probabilities were read or generated by this acquisition."]})
    if any(s["status"] != 200 for s in sources.values()):
        raise RuntimeError(f"Source unavailable, see {dest}")
    fixtures = json.loads((dest / "fixtures_raw.json").read_bytes())
    bootstrap = json.loads((dest / "bootstrap_raw.json").read_bytes())
    teams = {t["id"]: t["name"] for t in bootstrap["teams"]}
    prior = json.loads((ROOT / "data/prematch-intelligence/20261024_batch/fixtures.json").read_text(encoding="utf-8"))
    labels = {}
    for f in prior["fixtures"]:
        labels[f["home"]] = f["home_source_label"]
        labels[f["away"]] = f["away_source_label"]
    previous_games = {(f["home"], f["away"], f["kickoff"]) for f in prior["fixtures"]}
    candidates = [f for f in fixtures if f["kickoff_time"] is not None
                  and datetime.fromisoformat(f["kickoff_time"].replace("Z", "+00:00")) > now + timedelta(hours=24)
                  and (NAME.get(teams[f["team_h"]], teams[f["team_h"]]), NAME.get(teams[f["team_a"]], teams[f["team_a"]]), f["kickoff_time"]) not in previous_games]
    event = min(f["event"] for f in candidates if f["event"] is not None)
    selected = sorted([f for f in candidates if f["event"] == event], key=lambda f: (f["kickoff_time"], f["id"]))
    if len(selected) != 10 or any(f["started"] is not False or f["team_h_score"] is not None or f["team_a_score"] is not None for f in selected):
        raise ValueError("Next complete all-unstarted EPL round not available")
    rows, evidence, unknowns, observations = [], {}, {}, []
    for f in selected:
        home, away = [NAME.get(teams[f[k]], teams[f[k]]) for k in ("team_h", "team_a")]
        slug = lambda s: s.lower().replace(" & ", "-and-").replace(" ", "-")
        day = f["kickoff_time"][:10]
        fid = f"prematch:premier-league:{day}:{slug(home)}:{slug(away)}"
        rows.append({"match_id": fid, "home": home, "away": away, "competition": "Premier League",
            "kickoff": f["kickoff_time"], "neutral": False, "source_url": sources["fixtures"]["source_url"],
            "observed_at": sources["fixtures"]["received_at"], "published_at": None,
            "home_source_label": labels[home], "away_source_label": labels[away],
            "official_fixture_id": f["id"], "source_event": event,
            "source_access": "direct official FPL JSON response saved without modification",
            "verification_notes": ["Literal UTC kickoff, exact team IDs; selected before any prediction, all next complete round, not selected by outcome or odds."]})
        observations.append({"match_id": fid, "expected_kickoff": f["kickoff_time"], "official_fixture_id": f["id"],
            "home_team_id": f["team_h"], "away_team_id": f["team_a"], "started": f["started"],
            "finished": f["finished"], "team_h_score": f["team_h_score"], "team_a_score": f["team_a_score"]})
        facts = []
        for key, team in (("team_h", home), ("team_a", away)):
            tid = f[key]
            players = [{"id": p["id"], "name": p["first_name"] + " " + p["second_name"],
                "web_name": p["web_name"], "status": p["status"], "news": p.get("news"),
                "news_added": p.get("news_added"), "season_minutes": p.get("minutes"),
                "season_starts": p.get("starts"), "source_team_id": tid,
                "metadata_observed_at": sources["bootstrap"]["received_at"]}
                for p in bootstrap["elements"] if p["team"] == tid and (p["status"] != "a" or p.get("news"))]
            facts.append({"id": f"fpl-availability:{tid}:{now.strftime('%Y%m%dT%H%M%SZ')}",
                "url": sources["bootstrap"]["source_url"], "published_at": None,
                "observed_at": sources["bootstrap"]["received_at"], "claim_type": "fact", "team": team,
                "category": "availability", "status": "official_source_assertion", "source_kind": "direct_body",
                "source_team_id": tid, "source_players": players, "source_excerpt_path": "bootstrap_raw.json",
                "claim": f"Official FPL status/news and season participation counters for {team}. They describe a cached source snapshot, not confirmed future availability, starting XI, minutes forecasts or calibrated participation probabilities.",
                "retrieval_note": f"HTTP Date={sources['bootstrap'].get('response_date')}; Age={sources['bootstrap'].get('age_seconds')}; news_added is source metadata, not injury onset or verified publication time.",
                "limits": ["Status u includes transfer/registration/unavailable reasons and is not counted as injury.",
                    "No numeric FPL chance field is supplied or used as football outcome probability.",
                    "Current status may change before kickoff one week later; lack of a flag does not establish fitness."]})
            team_games = [g for g in fixtures if tid in (g["team_h"], g["team_a"]) and g["kickoff_time"] is not None]
            before = sorted([g for g in team_games if g["kickoff_time"] < f["kickoff_time"]], key=lambda g:g["kickoff_time"])
            after = sorted([g for g in team_games if g["kickoff_time"] > f["kickoff_time"]], key=lambda g:g["kickoff_time"])
            def schedule(g):
                return {"official_fixture_id": g["id"], "home": NAME.get(teams[g["team_h"]], teams[g["team_h"]]),
                        "away": NAME.get(teams[g["team_a"]], teams[g["team_a"]]), "kickoff": g["kickoff_time"],
                        "finished": g["finished"], "started": g["started"]}
            previous, following = schedule(before[-1]) if before else None, schedule(after[0]) if after else None
            facts.append({"id": f"fpl-league-schedule:{tid}:{f['id']}", "url": sources["fixtures"]["source_url"],
                "published_at": None, "observed_at": sources["fixtures"]["received_at"], "claim_type": "fact",
                "team": team, "category": "schedule", "status": "official_source_assertion", "source_kind": "direct_body",
                "claim": f"Saved official EPL schedule around this fixture for {team}: previous scheduled league match={json.dumps(previous, ensure_ascii=False)}; next scheduled league match={json.dumps(following, ensure_ascii=False)}. This source does not include cups or Europe, so these are not true all-competition rest or fatigue measures.",
                "league_schedule": {"previous": previous, "following": following},
                "limits": ["Cup/Europe and training/travel load not verified; do not infer competition priority or motivation from league schedule alone."]})
        evidence[fid] = facts
        unknowns[fid] = ["Early forecast about a week ahead; refresh separately before kickoff, retaining this original version.",
            "Cup/European fixtures and true all-competition rest not completely sourced in this packet.",
            "Confirmed starting XI, minutes, tactical plans and competition priority remain unknown.",
            "No verified current market quotes or opening-to-current movement in this acquisition."]
    write_json(dest / "fixtures.json", {"recorded_at": stamp(), "competition": "Premier League", "season": "2026/27", "matchweek": event,
        "policy": {"selection": "All ten fixtures in next complete unstarted EPL round after original ten, over24h away; no outcome/odds/model selection.",
                   "source_only": True, "original_unique_fixture_count": 10}, "fixtures": rows})
    write_json(dest / "news_evidence.json", {"recorded_at": stamp(), "evidence_by_fixture": evidence, "unknowns_by_fixture": unknowns})
    write_json(dest / "fixture_observations.json", {"recorded_at": stamp(), "fixture_observations": observations})
    write_json(dest / "market_unavailable.json", {"recorded_at": stamp(), "quotes": [], "limits": ["No verified source quote obtained in this source-only acquisition."]})
    print(json.dumps({"directory": str(dest), "event": event, "fixtures": rows, "team_count": len(teams), "source_metadata": sources}, ensure_ascii=False, indent=2))

if __name__ == "__main__":
    main()

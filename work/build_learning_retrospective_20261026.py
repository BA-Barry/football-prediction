def links_for_prefix(prefix):
    matches = sorted(p for p in (ROOT/'outputs').iterdir() if p.is_dir() and p.name.startswith(prefix))
    if not matches:
        raise RuntimeError('No evidence directory: '+prefix)
    return matches

def link(p, label=None):
    return '[' + (label or p.name) + '](<' + p.as_posix() + '>)'

for row in rows:
    dirs = sorted(set(p for prefix in row['directory_prefixes'] for p in links_for_prefix(prefix)))
    row['evidence_directories'] = [p.as_posix() for p in dirs]
    row['evidence_files'] = []
    for d in dirs:
        reports = sorted(d.glob('*.md'))
        # A directory is the evidence pointer where a report is absent, not a claim all raw files were read.
        row['evidence_files'].append((reports[0] if reports else d).as_posix())
    for mod in row['modules']:
        if not (SRC/(mod+'.py')).is_file():
            raise RuntimeError('No module '+mod)

